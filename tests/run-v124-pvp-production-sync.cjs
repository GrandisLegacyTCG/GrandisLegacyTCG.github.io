'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const read=r=>fs.readFileSync(path.join(root,r),'utf8');
const exists=r=>fs.existsSync(path.join(root,r));
const home=read('index.html'),html=read('pvp/index.html'),cfg=read('pvp/config.js'),app=read('pvp/js/app.bundle.js'),net=read('pvp/js/pvp-network.js'),css=read('pvp/css/app.css');
const meta=JSON.parse(read('pvp/PVP_FRONTEND_BUILD.json'));
assert.strictEqual(require('../package.json').version,'1.25.0');
assert.strictEqual(meta.pvp_version,'3.36');
assert.strictEqual(meta.build_id,'gl-pvp-3.36-2026-09-04');

// Verify the mirrored production payload against the manifest generated by the PvP source package.
const crypto=require('crypto');
const manifest=read('pvp/PVP_FRONTEND_SHA256.csv').trim().split(/\r?\n/).slice(1);
for(const line of manifest){
  const m=line.match(/^"((?:[^"]|"")*)","([0-9a-f]{64})","(\d+)"$/); assert(m,'invalid PvP frontend manifest row');
  const rel=m[1].replace(/""/g,'"'), expected=m[2], size=Number(m[3]); const abs=path.join(root,'pvp',rel);
  assert(fs.existsSync(abs),'Website /pvp missing manifest file '+rel); const buf=fs.readFileSync(abs);
  assert.strictEqual(buf.length,size,'Website /pvp size mismatch '+rel); assert.strictEqual(crypto.createHash('sha256').update(buf).digest('hex'),expected,'Website /pvp hash mismatch '+rel);
}
assert(html.includes('gl-pvp-3.36-direct-battle-feedback'),'production /pvp cache/build marker stale');
assert(cfg.includes("version:'Grandis Legacy PvP v3.36")&&cfg.includes("buildId:'gl-pvp-3.36-2026-09-04'"),'Website /pvp config is not PvP v3.36');
// The actual production frontend must contain the requested fixes.
assert(!html.includes('id="glMobileAppMenuButton"'),'static gameplay hamburger still embedded in production PvP HTML');
assert(net.includes('installPvpMobileMatchMenuController')&&net.includes('syncPvpMobileMatchMenuState'),'mobile lobby/match menu lifecycle missing');
assert(app.includes('pvp-player-display-name')&&net.includes('syncBattlefieldIdentityHeaders'),'live player-name battlefield binding missing');
assert(app.includes('pvp-net-signal')&&css.includes('.pvp-net-signal'),'connection signal indicator missing');
assert(net.includes('function battleFeedbackFromAuthoritativePlans(plans)'),'direct authoritative battle feedback mapper missing');
assert(net.includes('if(battleFeedback.length)playAuthoritativeBattleFeedbackAfterRender(battleFeedback)'),'post-render authoritative feedback playback missing');
assert(!net.includes('freshAuthoritativeBattleFeedback'),'obsolete canonical feedback-ledger diff still present');
assert(app.includes('pvp-identity-strip--opponent')&&app.includes('pvp-identity-strip--self'),'external identity/signal strip markup missing');
for(const f of ['pvp/assets/battle/P.Attack.png','pvp/assets/battle/M.Attack.png','pvp/assets/battle/P.Defense.png','pvp/assets/battle/M.Defense.png','pvp/assets/audio/battle/P.Atk.mp3','pvp/assets/audio/battle/M.Atk.mp3','pvp/assets/audio/battle/P.Def.mp3','pvp/assets/audio/battle/M.Def.mp3']) assert(exists(f),'production /pvp missing '+f);
// Plain anchors: no mobile JS routing is required to enter PvP from the Website.
const canonical='https://grandislegacytcg.github.io/pvp/';
assert((home.match(new RegExp(canonical.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'),'g'))||[]).length>=5,'Website PvP links are not canonical absolute anchors');
console.log('PASS Website v1.25: production /pvp mirrors PvP v3.36 features and mobile Play it Online uses canonical plain anchors.');
